"""Number the tiles of the Tiny Swords tilemap in ``docs/tileset.md`` and a reference image.

Run from the repository root: ``uv run --script scripts/tileset_reference.py``.
It reads the tile names from ``static/tileset.js``, rewrites the table between the
markers of ``docs/tileset.md`` and writes ``docs/tileset_reference.png``: the sheet
scaled up with each index printed in its cell. The image is derived from the asset
pack, so git ignores it.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
TILESET_SCRIPT = REPOSITORY_ROOT / "static" / "tileset.js"
TILEMAP_FILE = REPOSITORY_ROOT / "static/assets/Terrain/Tileset/Tilemap_color1.png"
DOCUMENT_FILE = REPOSITORY_ROOT / "docs" / "tileset.md"
REFERENCE_IMAGE_FILE = REPOSITORY_ROOT / "docs" / "tileset_reference.png"

TABLE_START = "<!-- tile table: generated by scripts/tileset_reference.py, do not edit -->"
TABLE_END = "<!-- end of the tile table -->"
REFERENCE_SCALE = 2
LABEL_FONT_SIZE = 22

TILE_BLOCK = re.compile(r"const TILESET_TILE = Object\.freeze\(\{(.*?)\}\);", re.DOTALL)
TILE_ENTRY = re.compile(r"\s*(\w+): (\d+), // (\w+) ?(.*)")
COLUMN_COUNT = re.compile(r"const TILESET_COLUMN_COUNT = (\d+);")
TILE_SIZE = re.compile(r"const TILESET_TILE_SIZE = (\d+);")


@dataclass(frozen=True)
class TilesetTile:
    name: str
    index: int
    guide_id: str
    note: str


@dataclass(frozen=True)
class Tileset:
    column_count: int
    tile_size: int
    tiles: list[TilesetTile]


def read_tileset() -> Tileset:
    """The tile names and sheet geometry declared in ``static/tileset.js``."""
    return parse_tileset(TILESET_SCRIPT.read_text(encoding="utf-8"))


def parse_tileset(source: str) -> Tileset:
    """The tile names and sheet geometry declared in the source of ``tileset.js``.

    Raises ``ValueError`` when a declaration is missing or a line of ``TILESET_TILE``
    is not an entry with its guide id comment.
    """
    block = TILE_BLOCK.search(source)
    column_count = COLUMN_COUNT.search(source)
    tile_size = TILE_SIZE.search(source)
    if block is None or column_count is None or tile_size is None:
        raise ValueError(f"{TILESET_SCRIPT} lost TILESET_TILE or its geometry constants")
    tiles = [parse_tile_entry(line) for line in block.group(1).splitlines() if line.strip()]
    return Tileset(int(column_count.group(1)), int(tile_size.group(1)), tiles)


def parse_tile_entry(line: str) -> TilesetTile:
    """One ``NAME: index, // guide_id note`` line of ``TILESET_TILE``; raises ``ValueError``."""
    entry = TILE_ENTRY.fullmatch(line)
    if entry is None:
        raise ValueError(f"{TILESET_SCRIPT.name}: not a TILESET_TILE entry: {line.strip()}")
    name, index, guide_id, note = entry.groups()
    return TilesetTile(name, int(index), guide_id, note)


def render_tile_table(tiles: list[TilesetTile], *, column_count: int, cell_count: int) -> str:
    """A markdown table with one row per cell of the sheet, empty cells included."""
    tile_by_index = {tile.index: tile for tile in tiles}
    rows = [
        "| Index | Col | Row | `TILESET_TILE` key | Guide id | Note |",
        "|---|---|---|---|---|---|",
    ]
    for index in range(cell_count):
        col, row = index % column_count, index // column_count
        tile = tile_by_index.get(index)
        if tile is None:
            rows.append(f"| {index} | {col} | {row} | empty | - |  |")
        else:
            rows.append(
                f"| {index} | {col} | {row} | `{tile.name}` | {tile.guide_id} | {escape_table_cell(tile.note)} |"
            )
    return "\n".join(rows)


def escape_table_cell(text: str) -> str:
    return text.replace("|", "\\|")


def replace_tile_table(document: str, table: str) -> str:
    """The document with the text between its table markers replaced by ``table``."""
    before, start, rest = document.partition(TABLE_START)
    _, end, after = rest.partition(TABLE_END)
    if not start or not end:
        raise ValueError(f"{DOCUMENT_FILE.name} lost its table markers")
    return f"{before}{TABLE_START}\n{table}\n{TABLE_END}{after}"


def count_sheet_cells(tileset: Tileset, *, sheet_size: tuple[int, int]) -> int:
    """The number of cells of a sheet of ``sheet_size`` pixels.

    Raises ``ValueError`` when the sheet does not have the columns ``tileset.js`` declares.
    """
    width, height = sheet_size
    if width != tileset.column_count * tileset.tile_size:
        raise ValueError(f"{TILEMAP_FILE.name} does not have the columns tileset.js declares")
    return tileset.column_count * (height // tileset.tile_size)


@dataclass(frozen=True)
class ReferenceCell:
    left: int
    top: int
    size: int
    label: str


def label_reference_cells(tileset: Tileset, *, cell_count: int) -> list[ReferenceCell]:
    """Each cell of the scaled reference image, with its index or "<index> empty"."""
    size = tileset.tile_size * REFERENCE_SCALE
    named = {tile.index for tile in tileset.tiles}
    return [
        ReferenceCell(
            left=(index % tileset.column_count) * size,
            top=(index // tileset.column_count) * size,
            size=size,
            label=str(index) if index in named else f"{index} empty",
        )
        for index in range(cell_count)
    ]


def draw_reference_image(tileset: Tileset) -> int:
    """Write the numbered sheet to ``REFERENCE_IMAGE_FILE``; return its cell count."""
    # Imported here so the tests can import this module without Pillow installed.
    from PIL import Image, ImageDraw, ImageFont

    with Image.open(TILEMAP_FILE) as sheet:
        cell_count = count_sheet_cells(tileset, sheet_size=sheet.size)
        scaled = sheet.convert("RGBA").resize(
            (sheet.width * REFERENCE_SCALE, sheet.height * REFERENCE_SCALE),
            Image.Resampling.NEAREST,
        )
    image = Image.new("RGBA", scaled.size, "white")
    image.alpha_composite(scaled)
    draw = ImageDraw.Draw(image)
    font = ImageFont.load_default(size=LABEL_FONT_SIZE)
    for cell in label_reference_cells(tileset, cell_count=cell_count):
        right, bottom = cell.left + cell.size - 1, cell.top + cell.size - 1
        draw.rectangle((cell.left, cell.top, right, bottom), outline="red")
        draw.text(
            (cell.left + 4, cell.top + 4),
            cell.label,
            fill="white",
            font=font,
            stroke_width=3,
            stroke_fill="black",
        )
    image.save(REFERENCE_IMAGE_FILE)
    return cell_count


def main() -> None:
    tileset = read_tileset()
    cell_count = draw_reference_image(tileset)
    table = render_tile_table(
        tileset.tiles, column_count=tileset.column_count, cell_count=cell_count
    )
    document = DOCUMENT_FILE.read_text(encoding="utf-8")
    DOCUMENT_FILE.write_text(replace_tile_table(document, table), encoding="utf-8")


if __name__ == "__main__":
    main()
